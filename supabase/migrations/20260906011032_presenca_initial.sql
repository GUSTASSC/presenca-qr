CREATE POLICY backend_only ON presenca.classes TO presenca_app USING (true) WITH CHECK (true);
CREATE POLICY backend_only ON presenca.students TO presenca_app USING (true) WITH CHECK (true);
CREATE POLICY backend_only ON presenca.sessions TO presenca_app USING (true) WITH CHECK (true);
