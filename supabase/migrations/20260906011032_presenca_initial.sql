 version text PRIMARY KEY, checksum text NOT NULL, applied_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE presenca._migrations ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON presenca._migrations FROM PUBLIC, anon, authenticated, service_role, presenca_app;
